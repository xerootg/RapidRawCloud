HEADER = "// @generated by protocol/rrcgen from protocol/rrcloud.protocol.toml — DO NOT EDIT.\n"

RUST_PRIM = {"u8": "u8", "u32": "u32", "u64": "u64", "i64": "i64", "usize": "usize", "bool": "bool", "string": "String"}


def rust_type(m: Model, t: TypeRef) -> str:
    if t.is_primitive:
        base = RUST_PRIM[t.name]
    else:
        kind = m.kind_of(t.name)
        if kind == "scalar" and m.scalars[t.name].kind != "string":
            base = {"i64": "i64", "u64": "u64"}[m.scalars[t.name].kind]
        else:
            base = t.name
    return f"Vec<{base}>" if t.array else base


def rust_literal(m: Model, t: TypeRef, v) -> str:
    if t.array:
        inner = ", ".join(rust_literal(m, TypeRef(t.name), x) for x in v)
        return f"vec![{inner}]"
    if t.name == "string":
        return f"{v!r}.to_string()".replace("'", '"')
    if t.name == "bool":
        return "true" if v else "false"
    return str(v)


def doc(text: str, indent: str = "") -> str:
    if not text:
        return ""
    return "".join(f"{indent}/// {line}\n" for line in text.splitlines())


def emit(m: Model, out_dir: Path) -> None:
    crate = out_dir / "rust" / "rrcloud-proto"
    (crate / "src").mkdir(parents=True, exist_ok=True)
    (crate / "Cargo.toml").write_text(CARGO_TOML, encoding="utf-8")
    (crate / "src" / "lib.rs").write_text(lib_rs(m), encoding="utf-8")


