def record_rs(m: Model, r: Record) -> str:
    o: list[str] = [doc(r.doc)]
    o.append("#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n")
    if r.naming == "camel":
        o.append('#[serde(rename_all = "camelCase")]\n')
    o.append(f"pub struct {r.name} {{\n")
    defaults: list[str] = []
    for f in r.fields:
        o.append(doc(f.doc, "    "))
        ty = rust_type(m, f.type)
        if f.optional:
            o.append('    #[serde(default, skip_serializing_if = "Option::is_none")]\n')
            o.append(f"    pub {f.name}: Option<{ty}>,\n")
        elif f.has_default:
            fname = f"default_{snake(r.name)}_{f.name}"
            o.append(f'    #[serde(default = "{fname}")]\n')
            o.append(f"    pub {f.name}: {ty},\n")
            defaults.append(f"fn {fname}() -> {ty} {{\n    {rust_literal(m, f.type, f.default)}\n}}\n")
        else:
            o.append(f"    pub {f.name}: {ty},\n")
    o.append("}\n\n")
    o.extend(defaults)
    if defaults:
        o.append("\n")
    o.append(f"impl {r.name} {{\n")
    o.append("    /// Serializes as one JSON document (deterministic: fixed field order, omitted `None`s).\n")
    o.append("    pub fn to_json(&self) -> Result<String, ProtoError> {\n        Ok(serde_json::to_string(self)?)\n    }\n")
    if r.version_field:
        vers = ", ".join(str(v) for v in r.supported_versions)
        o.append(f"    /// Versions this reader accepts in `{r.version_field}`.\n    pub const SUPPORTED_VERSIONS: &'static [u64] = &[{vers}];\n")
        o.append("    /// Decodes with the min-reader gate: an unsupported version is a typed error, never skipped.\n")
        o.append("    pub fn from_json(s: &str) -> Result<Self, ProtoError> {\n        Self::from_json_slice(s.as_bytes())\n    }\n")
        o.append("    pub fn from_json_slice(bytes: &[u8]) -> Result<Self, ProtoError> {\n")
        o.append("        let value: serde_json::Value = serde_json::from_slice(bytes)?;\n")
        o.append(f'        let version = match value.get("{r.version_field}") {{\n')
        o.append("            None => return Err(ProtoError::MissingVersion),\n")
        o.append("            Some(v) => v.as_u64().ok_or_else(|| ProtoError::MalformedVersion { value: v.to_string() })?,\n        };\n")
        o.append("        if !Self::SUPPORTED_VERSIONS.contains(&version) {\n            return Err(ProtoError::UnsupportedVersion { version });\n        }\n")
        o.append("        Ok(serde_json::from_value(value)?)\n    }\n")
    else:
        o.append("    pub fn from_json(s: &str) -> Result<Self, ProtoError> {\n        Ok(serde_json::from_str(s)?)\n    }\n")
        o.append("    pub fn from_json_slice(bytes: &[u8]) -> Result<Self, ProtoError> {\n        Ok(serde_json::from_slice(bytes)?)\n    }\n")
    o.append("}\n\n")
    return "".join(o)


def key_rs(m: Model, k) -> str:
    args = []
    for pname, ptype in k.params.items():
        if ptype in m.scalars:
            s = m.scalars[ptype]
            args.append(f"{pname}: &{ptype}" if s.kind == "string" else f"{pname}: {ptype}")
        elif ptype in m.enums:
            args.append(f"{pname}: {ptype}")
        else:
            args.append(f"{pname}: &str")
    o = [doc(k.doc), f"/// `{k.template}`\n", f"pub fn key_{k.name}({', '.join(args)}) -> String {{\n    let mut s = String::new();\n"]
    for p in k.parts:
        if p.literal is not None:
            o.append(f"    s.push_str({p.literal!r});\n".replace("'", '"'))
        elif p.fmt == "hex16":
            o.append(f'    s.push_str(&format!("{{:016x}}", {p.param}));\n')
        elif p.fmt == "blake3_32":
            o.append(f"    s.push_str(&blake3_32({p.param}.as_str()));\n")
        else:
            ptype = k.params[p.param]
            if ptype in m.enums:
                o.append(f"    s.push_str({p.param}.as_wire());\n")
            elif ptype in m.scalars and m.scalars[ptype].kind == "string":
                o.append(f"    s.push_str({p.param}.as_str());\n")
            elif ptype in m.scalars:
                o.append(f"    s.push_str(&{p.param}.to_string());\n")
            else:
                o.append(f"    s.push_str({p.param});\n")
    o.append("    s\n}\n\n")
    return "".join(o)


def documents_rs(m: Model) -> str:
    o: list[str] = ["// ---------------------------------------------------------------- documents\n\n"]
    for d in m.documents.values():
        enc = d.data.get("encoding")
        if enc == "ndjson":
            rec = d.data["record"]
            lim_e = next((l for l in d.data.get("limits", []) if "ENTRIES" in l), None)
            lim_b = next((l for l in d.data.get("limits", []) if "BYTES" in l), None)
            o.append(f"/// Encodes a `{d.name}` document: one `{rec}` JSON line per entry, newline-terminated.\n")
            o.append(f"pub fn encode_{d.name}(entries: &[{rec}]) -> Result<Vec<u8>, ProtoError> {{\n")
            if lim_e:
                o.append(f"    if entries.len() > {lim_e} {{\n        return Err(ProtoError::TooManyEntries {{ count: entries.len(), cap: {lim_e} }});\n    }}\n")
            o.append("    let mut out = Vec::new();\n    for e in entries {\n        out.extend_from_slice(e.to_json()?.as_bytes());\n        out.push(b'\\n');\n    }\n")
            if lim_b:
                o.append(f"    if out.len() > {lim_b} {{\n        return Err(ProtoError::TooLarge {{ size: out.len(), cap: {lim_b} }});\n    }}\n")
            o.append("    Ok(out)\n}\n\n")
            o.append(f"/// Decodes a `{d.name}` document fail-closed: the first unreadable line aborts the whole decode.\n")
            o.append(f"pub fn decode_{d.name}(bytes: &[u8]) -> Result<Vec<{rec}>, ProtoError> {{\n")
            if lim_b:
                o.append(f"    if bytes.len() > {lim_b} {{\n        return Err(ProtoError::TooLarge {{ size: bytes.len(), cap: {lim_b} }});\n    }}\n")
            o.append("    let mut out = Vec::new();\n    for line in bytes.split(|&b| b == b'\\n') {\n        if line.is_empty() {\n            continue;\n        }\n")
            if lim_e:
                o.append(f"        if out.len() == {lim_e} {{\n            return Err(ProtoError::TooManyEntries {{ count: out.len() + 1, cap: {lim_e} }});\n        }}\n")
            o.append(f"        out.push({rec}::from_json_slice(line)?);\n    }}\n    Ok(out)\n}}\n\n")
        elif enc == "gzip-ndjson":
            hdr = d.data["header"]
            rows = d.data["rows"]
            name = d.name.capitalize()
            lim_fetch = next((l for l in d.data.get("limits", []) if "FETCH" in l), None)
            lim_dec = next((l for l in d.data.get("limits", []) if "DECODED" in l), None)
            o.append(f"/// A decoded `{d.name}` document: header line, then rows.\n#[derive(Debug, Clone, PartialEq, Eq, Default)]\npub struct {name} {{\n    pub header: Option<{hdr}>,\n")
            for rr in rows:
                o.append(f"    pub {snake(rr)}s: Vec<{rr}>,\n")
            o.append("}\n\n")
            o.append(f"/// gzip NDJSON: header, then rows in declaration order. Deterministic for the same input.\n")
            o.append(f"pub fn encode_{d.name}(doc: &{name}) -> Result<Vec<u8>, ProtoError> {{\n    let mut nd = Vec::new();\n")
            o.append("    if let Some(h) = &doc.header {\n        nd.extend_from_slice(h.to_json()?.as_bytes());\n        nd.push(b'\\n');\n    }\n")
            for rr in rows:
                o.append(f"    for r in &doc.{snake(rr)}s {{\n        nd.extend_from_slice(r.to_json()?.as_bytes());\n        nd.push(b'\\n');\n    }}\n")
            o.append("    let mut enc = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::default());\n    enc.write_all(&nd)?;\n    Ok(enc.finish()?)\n}\n\n")
            o.append(f"/// Inflates (multi-member aware) and decodes fail-closed; row kind is chosen by which row record's first field is present.\n")
            o.append(f"pub fn decode_{d.name}(bytes: &[u8]) -> Result<{name}, ProtoError> {{\n")
            if lim_fetch:
                o.append(f"    if bytes.len() > {lim_fetch} {{\n        return Err(ProtoError::TooLarge {{ size: bytes.len(), cap: {lim_fetch} }});\n    }}\n")
            o.append("    let mut nd = Vec::new();\n    let mut dec = flate2::read::MultiGzDecoder::new(bytes);\n")
            if lim_dec:
                o.append(f"    dec.by_ref().take({lim_dec} as u64 + 1).read_to_end(&mut nd)?;\n    if nd.len() > {lim_dec} {{\n        return Err(ProtoError::TooLarge {{ size: nd.len(), cap: {lim_dec} }});\n    }}\n")
            else:
                o.append("    dec.read_to_end(&mut nd)?;\n")
            o.append(f"    let mut doc = {name}::default();\n    for (i, line) in nd.split(|&b| b == b'\\n').enumerate() {{\n        if line.is_empty() {{\n            continue;\n        }}\n")
            o.append("        if i == 0 {\n")
            o.append(f"            doc.header = Some({hdr}::from_json_slice(line)?);\n            continue;\n        }}\n")
            o.append("        let v: serde_json::Value = serde_json::from_slice(line)?;\n")
            first = True
            for rr in rows:
                disc = m.records[rr].fields[0].wire_name(m.records[rr].naming)
                kw = "if" if first else "} else if"
                o.append(f'        {kw} v.get("{disc}").is_some() {{\n            doc.{snake(rr)}s.push(serde_json::from_value(v)?);\n')
                first = False
            o.append('        } else {\n            return Err(ProtoError::ManifestLine { line: i + 1, reason: "row is neither a live nor a deleted row".into() });\n        }\n    }\n    Ok(doc)\n}\n\n')
    return "".join(o)
