"""C99 emitter: fixed-buffer structs, self-contained JSON encode/decode (no cJSON), validators, key builders.

Prefix: rrcp_ / RRCP_. Zero heap allocation; suitable for MCUs. Integers are exact
(own parser). The only external symbol is `rrcp_blake3_hook` for hashed key parts.
"""
from __future__ import annotations

from pathlib import Path

from model import Model, Record, Field, TypeRef, snake, upper_snake

HEADER = "/* @generated by protocol/rrcgen from protocol/rrcloud.protocol.toml — DO NOT EDIT. */\n"

C_PRIM = {"u8": "uint8_t", "u32": "uint32_t", "u64": "uint64_t", "i64": "int64_t", "usize": "size_t", "bool": "bool"}


def c_scalar_base(m: Model, name: str) -> str:
    """C type for a non-string, non-array leaf."""
    if name in C_PRIM:
        return C_PRIM[name]
    kind = m.kind_of(name)
    if kind == "scalar":
        return {"i64": "int64_t", "u64": "uint64_t"}[m.scalars[name].kind]
    if kind == "enum":
        return f"rrcp_{snake(name)}_t"
    if kind in ("map", "record"):
        return f"rrcp_{snake(name)}_t"
    raise ValueError(name)


def is_stringish(m: Model, t: TypeRef) -> bool:
    return t.name == "string" or (t.name in m.scalars and m.scalars[t.name].kind == "string")


def emit(m: Model, out_dir: Path) -> None:
    d = out_dir / "c"
    d.mkdir(parents=True, exist_ok=True)
    (d / "rrcloud_proto.h").write_text(header(m), encoding="utf-8")
    (d / "rrcloud_proto.c").write_text(source(m), encoding="utf-8")


def cdoc(text: str, indent: str = "") -> str:
    if not text:
        return ""
    lines = text.splitlines()
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {l}\n" for l in lines) + f"{indent} */\n"


def header(m: Model) -> str:
    o: list[str] = [HEADER]
    o.append(f"/* {m.protocol['description']} — protocol definition v{m.protocol['idl_version']}, wire version {m.protocol['wire_version']}. */\n")
    o.append("#pragma once\n#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
    o.append("/* ---- constants ---------------------------------------------------------- */\n")
    for c in m.constants.values():
        o.append(cdoc(c.doc))
        if c.type == "str":
            o.append(f'#define RRCP_{c.name} "{c.value}"\n')
        elif c.type.startswith("["):
            o.append(f"#define RRCP_{c.name}_LEN {len(c.value)}\nstatic const {C_PRIM[c.type[1:-1]]} RRCP_{c.name}[{len(c.value)}] = {{{', '.join(str(v) for v in c.value)}}};\n")
        else:
            suffix = {"u32": "u", "u64": "ull", "usize": "u", "i64": "ll"}.get(c.type, "")
            o.append(f"#define RRCP_{c.name} ({c.value}{suffix})\n")
    o.append("\n/* ---- errors ------------------------------------------------------------ */\n")
    o.append("typedef enum {\n    RRCP_OK = 0,\n    RRCP_E_INVALID = -1,            /**< a scalar failed validation */\n    RRCP_E_OVERFLOW = -2,           /**< output buffer or fixed-capacity field too small */\n"
             "    RRCP_E_SYNTAX = -3,             /**< malformed JSON */\n    RRCP_E_MISSING_FIELD = -4,      /**< a required field is absent */\n    RRCP_E_UNSUPPORTED_VERSION = -5,/**< version field outside the supported set (fail closed) */\n"
             "    RRCP_E_BAD_VALUE = -6,          /**< wrong JSON type / unknown enum value / integer out of range */\n} rrcp_err_t;\n\nconst char *rrcp_err_str(rrcp_err_t e);\n\n")
    o.append("/* ---- scalars ------------------------------------------------------------ */\n")
    for s in m.scalars.values():
        o.append(cdoc(s.doc))
        if s.kind == "string":
            o.append(f"#define RRCP_{upper_snake(s.name)}_MAX {s.buf_len}\n")
            o.append(f"rrcp_err_t rrcp_validate_{snake(s.name)}(const char *s);\n")
        else:
            o.append(f"typedef {C_PRIM[s.kind]} rrcp_{snake(s.name)}_t;\n")
    o.append("\n/* ---- enums --------------------------------------------------------------- */\n")
    for e in m.enums.values():
        o.append(cdoc(e.doc))
        o.append("typedef enum {\n")
        for v in e.values:
            o.append(f"    RRCP_{upper_snake(e.name)}_{v.name.upper()},{('  /**< ' + v.doc + ' */') if v.doc else ''}\n")
        o.append(f"    RRCP_{upper_snake(e.name)}__COUNT\n}} rrcp_{snake(e.name)}_t;\n")
        o.append(f"const char *rrcp_{snake(e.name)}_wire(rrcp_{snake(e.name)}_t v);\nbool rrcp_{snake(e.name)}_parse(const char *s, rrcp_{snake(e.name)}_t *out);\n\n")
    o.append("/* ---- maps ---------------------------------------------------------------- */\n")
    for mp in m.maps.values():
        o.append(cdoc(mp.doc))
        o.append(f"#define RRCP_{upper_snake(mp.name)}_MAX_ITEMS {mp.max_items}\n")
        o.append(f"typedef struct {{\n    size_t len;\n    struct {{\n        char key[RRCP_{upper_snake(mp.key)}_MAX + 1];\n        {C_PRIM[mp.value]} value;\n    }} items[{mp.max_items}];  /**< sorted by key */\n}} rrcp_{snake(mp.name)}_t;\n")
        o.append(f"/** Inserts/replaces (sorted). {'A zero value removes the key.' if mp.drop_zero else ''} */\nrrcp_err_t rrcp_{snake(mp.name)}_set(rrcp_{snake(mp.name)}_t *m, const char *key, {C_PRIM[mp.value]} value);\n")
        o.append(f"/** Missing keys read as 0. */\n{C_PRIM[mp.value]} rrcp_{snake(mp.name)}_get(const rrcp_{snake(mp.name)}_t *m, const char *key);\n\n")
    o.append("/* ---- records ------------------------------------------------------------- */\n")
    for r in m.records.values():
        o.append(record_h(m, r))
    o.append("/* ---- bucket keys --------------------------------------------------------- */\n")
    o.append("/** Provided by the integrator: BLAKE3-256 of `data` into `out` (used by hashed key parts). */\nextern void rrcp_blake3_hook(const uint8_t *data, size_t len, uint8_t out[32]);\n\n")
    for k in m.keys.values():
        o.append(cdoc(k.doc))
        o.append(f"/** `{k.template}` — returns length or a negative rrcp_err_t. */\nint rrcp_key_{k.name}({key_params_c(m, k)}char *out, size_t cap);\n\n")
    o.append("#ifdef __cplusplus\n}\n#endif\n")
    return "".join(o)


def key_params_c(m: Model, k) -> str:
    out = []
    for pname, ptype in k.params.items():
        if ptype in m.enums:
            out.append(f"rrcp_{snake(ptype)}_t {pname}")
        elif ptype in m.scalars and m.scalars[ptype].kind != "string":
            out.append(f"{C_PRIM[m.scalars[ptype].kind]} {pname}")
        else:
            out.append(f"const char *{pname}")
    return "".join(p + ", " for p in out)


def field_c_decl(m: Model, r: Record, f: Field) -> str:
    o = []
    if f.optional:
        o.append(f"    bool has_{f.name};\n")
    if f.type.array:
        o.append(f"    size_t {f.name}_len;\n")
        if is_stringish(m, TypeRef(f.type.name)):
            cap = f.max_length if f.type.name == "string" else m.scalars[f.type.name].buf_len
            o.append(f"    char {f.name}[{f.max_items}][{cap} + 1];\n")
        else:
            o.append(f"    {c_scalar_base(m, f.type.name)} {f.name}[{f.max_items}];\n")
    elif is_stringish(m, f.type):
        o.append(f"    char {f.name}[{m.string_buf_len(f)} + 1];\n")
    else:
        o.append(f"    {c_scalar_base(m, f.type.name)} {f.name};\n")
    return "".join(o)


def record_h(m: Model, r: Record) -> str:
    o = [cdoc(r.doc), "typedef struct {\n"]
    for f in r.fields:
        if f.doc:
            o.append(cdoc(f.doc, "    "))
        o.append(field_c_decl(m, r, f))
    o.append(f"}} rrcp_{snake(r.name)}_t;\n")
    o.append(f"/** Resets to defaults (zeroed, IDL defaults applied). */\nvoid rrcp_{snake(r.name)}_init(rrcp_{snake(r.name)}_t *v);\n")
    o.append(f"/** Validates scalars and writes one JSON document (fixed field order). Returns length or a negative rrcp_err_t. */\nint rrcp_{snake(r.name)}_encode(const rrcp_{snake(r.name)}_t *v, char *out, size_t cap);\n")
    o.append(f"/** Parses one JSON document (unknown fields ignored, required fields enforced{', version gate on `' + r.version_field + '`' if r.version_field else ''}). */\nrrcp_err_t rrcp_{snake(r.name)}_decode(const char *json, size_t len, rrcp_{snake(r.name)}_t *out);\n\n")
    return "".join(o)


