/*
 * Board pin maps. The board is chosen at build time (main/Kconfig.projbuild,
 * `CONFIG_RRC_BOARD_*`, set by the sdkconfig overlay the build uses). Common to
 * both Waveshare boards: ESP32-P4NRW32 (32 MB PSRAM), 32 MB NOR flash, the
 * ESP32-C6 on SDIO slot 1 (configured through esp_hosted Kconfig in
 * sdkconfig.defaults: CLK 18, CMD 19, D0..D3 14..17, reset 54), the microSD slot
 * on SDMMC slot 0 (CLK 43 CMD 44 D0..D3 39..42) and the internal I2C bus (SDA 7,
 * SCL 8).
 */
#pragma once
#include "sdkconfig.h"

#define BOARD_HOSTNAME_DEFAULT  "rrcloud-ingest"

#if CONFIG_RRC_BOARD_P4_POE_ETH || CONFIG_RRC_BOARD_P4_POE_ETH_DSI5
/* Waveshare ESP32-P4-WIFI6-POE-ETH (board wiki + schematic; cross-checked
 * against the espp BSP for the same board). */
#if CONFIG_RRC_BOARD_P4_POE_ETH_DSI5
#define BOARD_NAME              "ESP32-P4-WIFI6-POE-ETH + 5-inch DSI display"
#else
#define BOARD_NAME              "ESP32-P4-WIFI6-POE-ETH"
#endif

/* Ethernet: internal EMAC, RMII, IP101GRI PHY. REF_CLK is generated by the PHY
 * (25 MHz crystal) and fed INTO the P4 on GPIO50. */
#define BOARD_ETH_PHY_ADDR      1
#define BOARD_ETH_PHY_RST_GPIO  51
#define BOARD_ETH_MDC_GPIO      31
#define BOARD_ETH_MDIO_GPIO     52
#define BOARD_ETH_REFCLK_GPIO   50
#define BOARD_ETH_TX_EN_GPIO    49
#define BOARD_ETH_TXD0_GPIO     34
#define BOARD_ETH_TXD1_GPIO     35   /* shared with the BOOT strap */
#define BOARD_ETH_CRS_DV_GPIO   28
#define BOARD_ETH_RXD0_GPIO     29
#define BOARD_ETH_RXD1_GPIO     30

/* USB-A: USB 2.0 OTG High-Speed, host role. VBUS is always on (no enable GPIO). */
#if CONFIG_RRC_BOARD_P4_POE_ETH_DSI5
/* 15-pin MIPI-DSI connector (Raspberry Pi pinout) with an 800x480 "driver-free" Pi
 * touch display (main/panel_rpi_dsi.c): one data lane, the controller at 0x45 and
 * the FT5x06 touch at 0x38 on the internal I2C bus, which also reaches the DSI
 * connector (shared with the unused ES8311 codec at 0x18). VDD_MIPI_DPHY comes from
 * the P4's LDO_VO3 at 2.5 V (Waveshare BSP for the ESP32-P4-WIFI6 PoE boards). No
 * display reset or backlight GPIO: the panel's own controller does both. No user
 * key: BOOT (GPIO35) is RMII TXD1 once Ethernet runs. */
#define BOARD_LCD_H_RES         800
#define BOARD_LCD_V_RES         480
#define BOARD_LCD_DPI_CLK_MHZ   (240.0f / 9.0f)   /* PLL_F240M / 9; the DSI lane runs at 24x this */
#define BOARD_DSI_PHY_LDO_CHAN  3
#define BOARD_DSI_PHY_LDO_MV    2500
#define BOARD_I2C_SDA_GPIO      7
#define BOARD_I2C_SCL_GPIO      8
#endif

#elif CONFIG_RRC_BOARD_P4_TOUCH_LCD_43
/* Waveshare ESP32-P4-WIFI6-Touch-LCD-4.3 (schematic rev. of the board's GitHub
 * repository waveshareteam/ESP32-P4-WIFI6-Touch-LCD-4.3, cross-checked against its
 * BSP component esp32_p4_wifi6_touch_lcd_4_3 1.0.1). No Ethernet. */
#define BOARD_NAME              "ESP32-P4-WIFI6-Touch-LCD-4.3"

/* 4.3" IPS, 480x800 portrait, ST7701 over 2-lane MIPI-DSI (500 Mbit/s per lane,
 * 30 MHz DPI clock). The D-PHY is powered by the P4's on-chip LDO channel 3 at
 * 2.5 V. Panel reset on GPIO27. */
#define BOARD_LCD_H_RES         480
#define BOARD_LCD_V_RES         800
#define BOARD_LCD_RST_GPIO      27
#define BOARD_LCD_DSI_LANES     2
#define BOARD_LCD_DSI_LANE_MBPS 500
#define BOARD_LCD_DPI_CLK_MHZ   30
#define BOARD_DSI_PHY_LDO_CHAN  3
#define BOARD_DSI_PHY_LDO_MV    2500
/* Backlight: AP3032 boost. GPIO26 (LCD_BL_PWM) sets the level (LEDC duty; 100 % =
 * full brightness, as the vendor BSP drives it); GPIO33 (BL_EN, 100k pull-up on the
 * board) enables the boost converter, so driving it low really turns the LEDs off. */
#define BOARD_LCD_BL_PWM_GPIO   26
#define BOARD_LCD_BL_EN_GPIO    33

/* GT911 capacitive touch on the internal I2C bus (0x5D, or 0x14 depending on the
 * INT level at reset). Reset on GPIO23; the INT line is not routed (R35 is not
 * fitted), so the controller is polled. */
#define BOARD_I2C_SDA_GPIO      7
#define BOARD_I2C_SCL_GPIO      8
#define BOARD_TOUCH_RST_GPIO    23

/* BOOT key (Key2, active low, GPIO35). Only a strap at reset; afterwards it is a
 * free user button, used to sleep/wake the screen. The POWER key (Key3) is wired
 * to an EC23001 push-button power latch only: a short press powers the board on,
 * a 2 s press cuts power. The P4 cannot see it. */
#define BOARD_USER_KEY_GPIO     35

/* Li-ion cell on the MX1.25 "BAT" header, ETA6098 charger (its STAT pin only goes
 * to a test pad, so charge state is not observable). BAT_ADC = VBAT * 100k /
 * (200k + 100k) on GPIO20 = ADC1 channel 4. */
#define BOARD_BAT_ADC_GPIO      20
#define BOARD_BAT_ADC_CHANNEL   4      /* ADC_CHANNEL_4 on ADC_UNIT_1 */
#define BOARD_BAT_DIVIDER_NUM   3      /* VBAT = V(adc) * 3 */

/* USB: the "USB" Type-C is the P4's USB 2.0 OTG High-Speed port, but the board
 * wires it as a power sink (5.1k Rd on CC, VBUS into the 5 V rail through an
 * ideal diode): it never sources VBUS. A camera on it needs a USB-C OTG adapter
 * that injects external 5 V (README). */

#else
#error "no board selected: set CONFIG_RRC_BOARD_* (main/Kconfig.projbuild)"
#endif
